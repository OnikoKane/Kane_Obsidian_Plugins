  /* ---------------- 索引 ---------------- */
  async rebuildIndex() {
    if (this.rebuilding)
      return;
    this.rebuilding = true;
    try {
      const folder = (this.settings.cardFolder ?? "").replace(/\\/g, "/").replace(/^\/+|\/+$/g, "");
      const files = this.app.vault.getMarkdownFiles().filter((file) => {
        if (!folder)
          return true;
        return file.path === folder || file.path.startsWith(`${folder}/`);
      });
      const entries = await Promise.all(
        files.map(async (file) => ({
          path: file.path,
          content: await this.app.vault.cachedRead(file)
        }))
      );
      this.index = buildIndex(entries, {
        defaultSubject: this.settings.defaultSubject,
        cardFolder: this.settings.cardFolder
      });
      this.syncStates();
      this.refreshAll();
    } catch (error) {
      console.error("[ZapTrace] \u91CD\u5EFA\u7D22\u5F15\u5931\u8D25", error);
      new import_obsidian8.Notice("ZapTrace: \u91CD\u5EFA\u7D22\u5F15\u5931\u8D25\uFF0C\u8BE6\u89C1\u63A7\u5236\u53F0");
    } finally {
      this.rebuilding = false;
    }
  }
  scheduleRebuild() {
    if (this.rebuildTimer !== null)
      clearTimeout(this.rebuildTimer);
    this.rebuildTimer = window.setTimeout(() => {
      this.rebuildTimer = null;
      void this.rebuildIndex();
    }, 500);
  }
  /**
   * 同步卡片缓存到 data.json（仅缓存变化时保存，避免写放大，C11）。
   */
  syncStates() {
    const now = this.nowIso();
    const orphanBefore = Object.entries(this.data.questions).map(([qid, state]) => `${qid}:${state.orphaned ? 1 : 0}`).sort().join(",");
    const cardSignature = this.index.cards.map(
      (card) => `${card.key}|${card.qid}|${card.stemHash}|${card.file}|${card.subject}|${card.tags.join(",")}|${card.source}|${card.starInitial ? 1 : 0}`
    ).sort().join("\n");
    for (const card of this.index.cards) {
      ensureQuestionFromCard(this.data, card, now);
    }
    markOrphans(this.data, new Set(this.index.cards.map((card) => card.qid)));
    const orphanAfter = Object.entries(this.data.questions).map(([qid, state]) => `${qid}:${state.orphaned ? 1 : 0}`).sort().join(",");
    const signature = `${cardSignature}
#
${orphanBefore}
#
${orphanAfter}`;
    this.data.meta.lastScanAt = now;
    if (signature !== this.lastSignature) {
      this.lastSignature = signature;
      this.store.markDirty();
    }
  }
  /* ---------------- 渲染 ---------------- */
  renderCodeBlock(source, el, ctx) {
    const filePath = ctx.sourcePath;
    const info = ctx.getSectionInfo(el);
    const startLine = info ? info.lineStart + 1 : 1;
    const endLine = info ? info.lineEnd + 1 : startLine;
    let card = this.findCardByLocation(filePath, startLine);
    if (!card) {
      const parsed = parseBlockInner(
        filePath,
        source.split(/\r?\n/),
        startLine,
        endLine,
        { blockIndex: 0 }
      );
      card = parsed.card ?? void 0;
    }
    if (!card)
      return;
    const owner = new RenderScope(el);
    ctx.addChild(owner);
    const inSourceView = Boolean(el.closest(".markdown-source-view"));
    if (inSourceView) {
      if (this.settings.livePreview === "source")
        return;
      renderQuestionCard({ plugin: this, card, host: el, owner, compact: true });
      return;
    }
    renderQuestionCard({ plugin: this, card, host: el, owner });
  }
  /* ---------------- 命令辅助 ---------------- */
  practiceCurrentCard(editor, file) {
    if (!file)
      return;
    const cursorLine = editor.getCursor().line + 1;
    const scanned = scanZaptraceBlocks(file.path, editor.getValue());
    const located = scanned.cards.find(
      (card) => cursorLine >= card.line && cursorLine <= card.endLine
    );
    if (!located) {
      new import_obsidian8.Notice("ZapTrace: \u5149\u6807\u4E0D\u5728 zaptrace \u9898\u5361\u5185");
      return;
    }
    const indexed = this.index.cards.find(
      (card) => card.file === located.file && card.line === located.line
    ) ?? located;
    void this.startPractice([indexed]);
  }
  randomPractice() {
    const cards = this.index.cards;
    if (cards.length === 0) {
      new import_obsidian8.Notice("ZapTrace: \u8FD8\u6CA1\u6709\u53EF\u7EC3\u4E60\u7684\u9898\u5361");
      return;
    }
    const random = cards[Math.floor(Math.random() * cards.length)];
    void this.startPractice([random]);
  }
  async writeBackup(name, content) {
    const dir = this.manifest.dir;
    if (!dir)
      return;
    await this.app.vault.adapter.write(`${dir}/${name}`, content);
  }
