// src/core/practice.ts
var PracticeSession = class {
  constructor(cards) {
    this.cursor = 0;
    this.phase = "viewing";
    this.counts = {
      again: 0,
      hard: 0,
      good: 0,
      easy: 0
    };
    this.shownAt = null;
    this.queue = [...cards];
  }
  get total() {
    return this.queue.length;
  }
  get position() {
    return this.cursor;
  }
  get finished() {
    return this.cursor >= this.queue.length;
  }
  get current() {
    return this.queue[this.cursor] ?? null;
  }
  get canReveal() {
    return this.phase === "viewing" && this.current !== null;
  }
  get canRate() {
    return this.phase === "revealed" && this.current !== null;
  }
  progress() {
    return { position: Math.min(this.cursor + 1, this.total), total: this.total };
  }
  /** 记录「题干显示时刻」，用于 elapsedMs。重复调用不覆盖。 */
  markShown(nowMs) {
    if (this.shownAt === null)
      this.shownAt = nowMs;
  }
  reveal() {
    if (this.phase !== "viewing")
      return false;
    this.phase = "revealed";
    return true;
  }
  /**
   * 评分。**只有 revealed 状态才允许**；viewing / rated 状态返回 null，
   * 且不会调用 recordReview，因此 data.json 不会被写（H4 硬约束）。
   */
  rate(data, rating, ctx2) {
    const card = this.current;
    if (!card)
      return null;
    if (this.phase !== "revealed")
      return null;
    const result = recordReview(data, card, rating, ctx2);
    this.counts[rating] += 1;
    this.phase = "rated";
    return result;
  }
  /** 进入下一题；返回是否还有题可练。 */
  advance() {
    this.cursor += 1;
    this.phase = "viewing";
    this.shownAt = null;
    return !this.finished;
  }
  /** 跳过本题（不写 data.json）。 */
  skip() {
    return this.advance();
  }
  elapsedMs(nowMs) {
    if (this.shownAt === null)
      return null;
    return Math.max(0, nowMs - this.shownAt);
  }
  summary() {
    const { again, hard, good, easy } = this.counts;
    const total = again + hard + good + easy;
    return `\u672C\u6B21 ${total} \u9898\uFF0C\u5FD8\u8BB0 ${again} / \u56F0\u96BE ${hard} / \u60F3\u8D77 ${good} / \u79D2\u7B54 ${easy}`;
  }
};

