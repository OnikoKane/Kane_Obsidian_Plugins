// src/core/filter.ts
function matchesFilter(card, state, filter, today) {
  if (filter.starredOnly && !(state?.star ?? false))
    return false;
  if (filter.subject && card.subject !== filter.subject)
    return false;
  if (filter.tags.length > 0) {
    for (const tag of filter.tags) {
      if (!card.tags.includes(tag))
        return false;
    }
  }
  const search = filter.search.trim().toLowerCase();
  if (search !== "") {
    const haystack = `${card.stem}
${card.tags.join(" ")}`.toLowerCase();
    if (!haystack.includes(search))
      return false;
  }
  switch (filter.time) {
    case "all":
      break;
    case "overdue":
      if (!state || !state.due)
        return false;
      if (!(state.due < today))
        return false;
      break;
    case "today":
      if (!state || state.due !== today)
        return false;
      break;
    case "week": {
      const limit = addDays(today, 7);
      if (!state || !state.due)
        return false;
      if (!(state.due > today && state.due <= limit))
        return false;
      break;
    }
    case "unrated":
      if (state?.due)
        return false;
      break;
  }
  return true;
}
function filterCards(cards, data, filter, today) {
  return cards.filter(
    (card) => matchesFilter(card, data.questions[card.qid], filter, today)
  );
}
function compareDue(a, b) {
  const da = a?.due ?? null;
  const db = b?.due ?? null;
  if (da === db)
    return 0;
  if (da === null)
    return 1;
  if (db === null)
    return -1;
  return da < db ? -1 : 1;
}
function sortCards(cards, data, sort, _today) {
  const copy = [...cards];
  copy.sort((a, b) => {
    const sa = data.questions[a.qid];
    const sb = data.questions[b.qid];
    switch (sort) {
      case "starred": {
        const starredA = sa?.star ? 1 : 0;
        const starredB = sb?.star ? 1 : 0;
        if (starredA !== starredB)
          return starredB - starredA;
        const due = compareDue(sa, sb);
        if (due !== 0)
          return due;
        return a.qid < b.qid ? -1 : a.qid > b.qid ? 1 : 0;
      }
      case "recent": {
        const ta = sa?.firstSeenAt ?? "";
        const tb = sb?.firstSeenAt ?? "";
        if (ta !== tb)
          return ta < tb ? 1 : -1;
        return a.qid < b.qid ? -1 : a.qid > b.qid ? 1 : 0;
      }
      case "subject": {
        const c = a.subject.localeCompare(b.subject, "zh-Hans-CN");
        if (c !== 0)
          return c;
        const due = compareDue(sa, sb);
        if (due !== 0)
          return due;
        return a.qid < b.qid ? -1 : a.qid > b.qid ? 1 : 0;
      }
      case "due":
      default: {
        const due = compareDue(sa, sb);
        if (due !== 0)
          return due;
        return a.qid < b.qid ? -1 : a.qid > b.qid ? 1 : 0;
      }
    }
  });
  return copy;
}
