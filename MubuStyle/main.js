function scanInlineTags(before, selection, after) {
  const text = `${before}${selection}${after}`;
  const end = before.length + selection.length;
  const re = /<mark[^>]*class="[^"]*mubu-hl[^"]*"[^>]*>|<\/mark>|<span[^>]*class="[^"]*mubu-fg-(\w+)[^"]*"[^>]*>|<\/span>/g;
  let mark = false;
  let color = null;
  let match;
  while (match = re.exec(text)) {
    if (match.index >= end)
      break;
    const tag = match[0];
    if (tag.startsWith("</mark>")) {
      mark = false;
    } else if (tag.startsWith("<mark")) {
      mark = true;
    } else if (tag.startsWith("</span>")) {
      color = null;
    } else {
      const id = match[1];
      color = TEXT_COLORS.some(([name]) => name === id) ? id : null;
    }
  }
  const tail = text.slice(end);
  if (mark && !tail.includes("</mark>") && !selection.includes("</mark>")) {
    mark = false;
  }
  if (color && !tail.includes("</span>") && !selection.includes("</span>")) {
    color = null;
  }
  if (!mark && /<mark[^>]*class="[^"]*mubu-hl/.test(selection))
    mark = true;
  if (!color) {
    const hit = selection.match(
      /<span[^>]*class="[^"]*mubu-fg-(\w+)[^"]*"[^>]*>/
    );
    if (hit) {
      const id = hit[1];
      if (TEXT_COLORS.some(([name]) => name === id))
        color = id;
    }
  }
  return { highlight: mark, color };
}
